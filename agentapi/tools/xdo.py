from agentapi.meta_tools.interface.hotplug_tool import hotplug_tool


class Xdo(hotplug_tool):
    def get_schema(self) -> dict:
        return {'type': 'function', 'function': {'name': 'xdo', 'description': '通过 XTEST(X11) 向桌面注入鼠标/键盘事件：支持 click/doubleclick/move/type/key/paste(剪贴板粘贴，可输入中文)/sleep。用法：xdo click 2200 190 / xdo paste 收到 / xdo key Return / xdo key v ctrl。', 'parameters': {'items': {'type': 'string'}, 'type': 'array', 'description': '位置参数：命令 + 参数，例如 ["click","2200","190"]、["paste","收到"]、["key","v","ctrl"]'}}}

    def run(self, *args, **kwargs):
        import json, subprocess, os

        L = [
        "#!/usr/bin/env python3",
        "import sys, time, os, subprocess",
        "from Xlib import X, XK, display, Xatom",
        "from Xlib import protocol as xproto",
        "from Xlib.ext import xtest",
        "",
        "d = display.Display()",
        "",
        "def pause(t=0.06):",
        "    d.sync(); time.sleep(t)",
        "",
        "def move(x, y):",
        "    xtest.fake_input(d, X.MotionNotify, x=int(x), y=int(y)); pause(0.08)",
        "",
        "def click(x, y, button=1):",
        "    move(x, y)",
        "    xtest.fake_input(d, X.ButtonPress, button); pause(0.06)",
        "    xtest.fake_input(d, X.ButtonRelease, button); pause(0.2)",
        "",
        "def spare_keycode():",
        "    mn = d.display.info.min_keycode",
        "    mx = d.display.info.max_keycode",
        "    mapping = d.get_keyboard_mapping(mn, mx - mn + 1)",
        "    for i, syms in enumerate(mapping):",
        "        if not any(syms):",
        "            return mn + i",
        "    return mx",
        "",
        "def type_text(s):",
        "    spare = spare_keycode()",
        "    for ch in s:",
        "        cp = ord(ch)",
        "        ks = cp if cp < 0x100 else 0x01000000 + cp",
        "        d.change_keyboard_mapping(spare, [[ks, ks, ks, ks]])",
        "        d.sync(); time.sleep(0.03)",
        "        xtest.fake_input(d, X.KeyPress, spare); d.sync(); time.sleep(0.03)",
        "        xtest.fake_input(d, X.KeyRelease, spare); d.sync(); time.sleep(0.05)",
        "    d.change_keyboard_mapping(spare, [[0, 0, 0, 0]]); d.sync()",
        "",
        "def _kc(name):",
        "    return d.keysym_to_keycode(XK.string_to_keysym(name))",
        "",
        "def key(names, ctrl=False, shift=False, alt=False):",
        "    if isinstance(names, str):",
        "        names = [names]",
        "    mods = []",
        "    if ctrl: mods.append(_kc('Control_L'))",
        "    if shift: mods.append(_kc('Shift_L'))",
        "    if alt: mods.append(_kc('Alt_L'))",
        "    for m in mods:",
        "        xtest.fake_input(d, X.KeyPress, m); d.sync()",
        "    for n in names:",
        "        kc = _kc(n)",
        "        xtest.fake_input(d, X.KeyPress, kc); d.sync(); time.sleep(0.04)",
        "        xtest.fake_input(d, X.KeyRelease, kc); d.sync(); time.sleep(0.06)",
        "    for m in reversed(mods):",
        "        xtest.fake_input(d, X.KeyRelease, m); d.sync()",
        "    pause(0.2)",
        "",
        "def serve_clipboard(text, hold):",
        "    root = d.screen().root",
        "    w = root.create_window(-10, -10, 1, 1, 0, d.screen().root_depth, X.InputOutput, X.CopyFromParent)",
        "    CLIP = d.intern_atom('CLIPBOARD')",
        "    UTF8 = d.intern_atom('UTF8_STRING')",
        "    TARGETS = d.intern_atom('TARGETS')",
        "    TEXT = d.intern_atom('TEXT')",
        "    data = text.encode('utf-8')",
        "    w.set_selection_owner(CLIP, X.CurrentTime)",
        "    d.sync()",
        "    end = time.time() + hold",
        "    while time.time() < end:",
        "        if not d.pending_events():",
        "            time.sleep(0.05); continue",
        "        e = d.next_event()",
        "        if e.type != X.SelectionRequest:",
        "            continue",
        "        prop = e.property",
        "        if prop == X.NONE:",
        "            prop = e.target",
        "        ok = True",
        "        try:",
        "            if e.target == TARGETS:",
        "                e.requestor.change_property(prop, Xatom.ATOM, 32, [UTF8, TEXT, Xatom.STRING])",
        "            elif e.target in (UTF8, TEXT):",
        "                e.requestor.change_property(prop, UTF8, 8, data)",
        "            else:",
        "                ok = False",
        "        except Exception:",
        "            ok = False",
        "        ev = xproto.event.SelectionNotify(time=e.time, requestor=e.requestor, selection=e.selection, target=e.target, property=(prop if ok else 0))",
        "        e.requestor.send_event(ev, event_mask=0)",
        "        d.sync()",
        "        end = time.time() + hold",
        "",
        "def paste(text, hold=30):",
        "    subprocess.Popen([sys.executable, os.path.abspath(__file__), 'clip', text, str(hold)],",
        "                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)",
        "    time.sleep(1.0)",
        "    key('v', ctrl=True)",
        "",
        "cmd = sys.argv[1]",
        "a = sys.argv[2:]",
        "if cmd == 'click':",
        "    click(int(a[0]), int(a[1]))",
        "elif cmd == 'doubleclick':",
        "    click(int(a[0]), int(a[1])); time.sleep(0.05); click(int(a[0]), int(a[1]))",
        "elif cmd == 'move':",
        "    move(int(a[0]), int(a[1]))",
        "elif cmd == 'type':",
        "    type_text(a[0])",
        "elif cmd == 'key':",
        "    flags = set(a[1:])",
        "    key(a[0], ctrl='ctrl' in flags, shift='shift' in flags, alt='alt' in flags)",
        "elif cmd == 'paste':",
        "    paste(a[0])",
        "elif cmd == 'clip':",
        "    serve_clipboard(a[0], float(a[1]))",
        "elif cmd == 'sleep':",
        "    time.sleep(float(a[0]))",
        "if cmd != 'clip':",
        "    print('ok')",
        ]

        script = "\n".join(L) + "\n"
        with open("/tmp/xdo.py", "w") as f:
            f.write(script)
        argv = [str(x) for x in (args if args else (kwargs.get("args") or []))]
        env = {**os.environ, "DISPLAY": os.environ.get("DISPLAY", ":0")}
        try:
            p = subprocess.run(["/home/sdjini/Projects/reSEN-Agent/.venv/bin/python", "/tmp/xdo.py"] + argv,
                               capture_output=True, text=True, timeout=120, env=env)
            return json.dumps({"rc": p.returncode, "stdout": p.stdout[-4000:], "stderr": p.stderr[-4000:]}, ensure_ascii=False, indent=2)
        except Exception as e:
            return json.dumps({"error": type(e).__name__ + ": " + str(e)}, ensure_ascii=False)
